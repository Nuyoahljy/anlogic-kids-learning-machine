def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def write_json(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def make_preview(path, item, ids, bitmaps, font_path, *, quiz=False, healthy=True):
    """Render the six specified text rows from asset bitmaps; not an RTL capture."""
    canvas = Image.new("RGB", (1280, 776), "#38424A")
    draw = ImageDraw.Draw(canvas)
    for top in (8, 608):
        draw.rectangle((32, top, 1247, top+103), fill="#18242C")
    draw.rectangle((320, 120, 959, 599), outline="#73838C", width=2)
    annotation = ImageFont.truetype(str(font_path), 22, index=0)
    draw.text((370, 350), "中心识别区占位：实际内容来自摄像头", font=annotation, fill="#BECBD2")
    lines = [
        ("问答模式" if quiz else "探索模式") + "  题号 " + ("03" if quiz else "--") + "/10   分数 02/10",
        TEXTS[8], TEXTS[9],
        (TEXTS[14] + TEXTS[41]) if quiz else TEXTS[13],
        TEXTS[42] if not healthy else (TEXTS[22] if quiz else TEXTS[24]),
        TEXTS[43] if not healthy else TEXTS[25] + TEXTS[27+item],
    ]
    tones = [1, 1, 0, 1 if quiz else 0, 2 if not healthy else 0, 2 if not healthy else 0]
    colors = ["#F5F7FA", "#ABE8F2", "#FFE3A3", "#9EF0CC"]
    for line, (text, tone) in enumerate(zip(lines, tones)):
        assert len(text) <= 37
        y = 12+line*32 if line < 3 else 612+(line-3)*32
        for col, char in enumerate(text):
            if char == " ":
                continue
            mask = bitmaps[ids[char]].resize((32,32), Image.Resampling.NEAREST)
            canvas.paste(colors[tone], (48+32*col, y), mask)
    draw.rectangle((0, 720, 1279, 775), fill="#E4EAF0")
    label = ("问答目标：雨伞；当前识别：" + TEXTS[27+item]) if quiz else "探索对象：" + TEXTS[27+item]
    if not healthy:
        label += "；识别健康信号无效，已隐藏旧结果"
    draw.text((32, 733), "软件显示预览（非板上画面）  " + label, font=annotation, fill="#253746")
    canvas.save(path)
    return {"path": path.name, "item_id": item, "mode": 2 if quiz else 1,
            "target_item": 14 if quiz else 0, "result_healthy": healthy, "lines": lines,
            "sha256": sha256(path)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/simsun.ttc"))
    args = parser.parse_args()
    repo = Path(__file__).resolve().parents[3]
    rtl_dir = repo / "fpga/rtl/sc520-card-recognition/items14"
    assets_dir = repo / "assets/templates/sc520-card-recognition/items14"
    font = ImageFont.truetype(str(args.font), 16, index=0)
    if font.getname()[0].lower() not in ("simsun", "宋体"):
        raise ValueError("Required SimSun face unavailable; no silent fallback")
    font_hash = sha256(args.font)
    reserved = " -/0123456789"
    chars = sorted(set("".join(TEXTS)) - set(reserved))
    available = [i for i in range(1, 256) if i not in map(ord, reserved)]
    if len(chars) > len(available):
        raise ValueError("8-bit glyph space exhausted")
    ids = {c: ord(c) for c in reserved}
    ids.update(dict(zip(chars, available)))
    bitmaps, font_rows = {}, {}
    for char, code in sorted(ids.items(), key=lambda pair: pair[1]):
        bitmap = Image.new("L", (16,16), 0)
        if char != " ":
            box = font.getbbox(char)
            width, height = box[2]-box[0], box[3]-box[1]
            if width > 16 or height > 16:
                raise ValueError(f"Glyph exceeds 16x16: {char!r} {box}")
            ImageDraw.Draw(bitmap).text(((16-width)//2-box[0], (16-height)//2-box[1]), char, font=font, fill=255)
        bitmap = bitmap.point(lambda value: 255 if value >= 128 else 0)
        rows = [sum(1 << (15-x) for x in range(16) if bitmap.getpixel((x,y))) for y in range(16)]
        if char != " " and not any(rows):
            raise ValueError("Empty glyph: " + char)
        bitmaps[code], font_rows[code] = bitmap, rows
    rtl_dir.mkdir(parents=True, exist_ok=True)
    assets_dir.mkdir(parents=True, exist_ok=True)
    text_manifest = {
        "schema_version": 1, "encoding": "UTF-8", "columns": 37,
        "texts": [{"id": tid, "text": text, "glyph_ids": [ids[c] if c != " " else 0 for c in text]} for tid, text in enumerate(TEXTS)],
        "items": [{"item_id": item, "text_id": 27+item, "name": TEXTS[27+item]} for item in range(1,15)],
        "unknown_item_ids": [0, 15], "unknown_text_id": 27,
        "unhealthy_text_ids": [42, 43],
    }
    write_json(assets_dir / "text-manifest.json", text_manifest)
    # Golden text declarations are derived by re-reading the human-readable
    # manifest. They do not parse or call the RTL selectors or text function.
    manifest = json.loads((assets_dir / "text-manifest.json").read_text(encoding="utf-8"))
    text_ref = ["// Golden glyph sequences from text-manifest.json, independent of RTL addressing.",
                "function automatic integer items14_ref_text(input integer tid, input integer pos);",
                "begin", "items14_ref_text=0;", "case(tid)"]
    table = ["    function [7:0] text_glyph;", "        input [5:0] text_id,position;", "        begin",
             "            text_glyph=0;", "            case({text_id,position})"]
    for row in manifest["texts"]:
        tid, text = row["id"], row["text"]
        if len(text) > 37:
            raise ValueError(f"Text {tid} exceeds viewport")
        text_ref.extend([f"{tid}: begin", "case(pos)"])
        for pos, code in enumerate(row["glyph_ids"]):
            if code:
                table.append(f"                12'd{tid*64+pos}: text_glyph=8'd{code};")
                text_ref.append(f"{pos}: items14_ref_text={code};")
        text_ref.extend(["default: items14_ref_text=0;", "endcase", "end"])
    table.extend(["            endcase", "        end", "    endfunction"])
    text_ref.extend(["endcase", "end", "endfunction",
                     "function automatic integer items14_ref_item(input integer item, input integer pos);",
                     "begin", "case(item)"])
    for item in manifest["items"]:
        text_ref.append(f"{item['item_id']}: items14_ref_item=items14_ref_text({item['text_id']},pos);")
    text_ref.extend([f"default: items14_ref_item=items14_ref_text({manifest['unknown_text_id']},pos);",
                     "endcase", "end", "endfunction", ""])
    (rtl_dir / "items14_content.v").write_text(CONTENT.replace("@@TABLE@@", "\n".join(table)), encoding="ascii")
    (assets_dir / "items14_text_reference.svh").write_text("\n".join(text_ref), encoding="ascii")
    header = f"// Local SimSun 16px, threshold 128; system font SHA256 {font_hash}."
    rom = [header, "// Generated candidate: 4096x16, synchronous read, no reset on memory.",
           "module items14_font_rom(input wire clk,input wire [7:0] glyph,input wire [3:0] row,output reg [15:0] bits);",
           '(* ram_style = "bram" *) reg [15:0] rom [0:4095];', "initial begin"]
    for address in range(4096):
        code, row = divmod(address,16)
        bits = font_rows.get(code,[0]*16)[row]
        rom.append(f"    rom[12'd{address}]=16'h{bits:04X};")
    rom.extend(["end", "always @(posedge clk) bits <= rom[{glyph,row}];", "endmodule", ""])
    (rtl_dir / "items14_font_rom.v").write_text("\n".join(rom), encoding="ascii")
    bitmap_ref = [header, "// Golden full bitmaps: MSB is top-left, addressing is independent of ROM rows.",
                  "function automatic [255:0] items14_ref_bitmap(input integer glyph_id);", "begin",
                  "items14_ref_bitmap=0;", "case(glyph_id)"]
    for code, rows in font_rows.items():
        bitmap_ref.append(f"{code}: items14_ref_bitmap=256'h{''.join(f'{row:04X}' for row in rows)};")
    bitmap_ref.extend(["endcase", "end", "endfunction", ""])
    (assets_dir / "items14_bitmap_reference.svh").write_text("\n".join(bitmap_ref), encoding="ascii")
    previews = [make_preview(assets_dir / f"preview-explore-{item:02}.png", item, ids, bitmaps, args.font) for item in range(10,15)]
    previews.append(make_preview(assets_dir / "preview-quiz.png", 10, ids, bitmaps, args.font, quiz=True))
    previews.append(make_preview(assets_dir / "preview-unhealthy.png", 10, ids, bitmaps, args.font, quiz=True, healthy=False))
    output_paths = [rtl_dir / "items14_content.v", rtl_dir / "items14_font_rom.v", assets_dir / "text-manifest.json",
                    assets_dir / "items14_text_reference.svh", assets_dir / "items14_bitmap_reference.svh"]
    write_json(assets_dir / "font-manifest.json", {
        "schema_version": 1, "status": "候选素材；预览非板上画面；硬件资源与时序待验证",
        "font_path": str(args.font), "font_face": font.getname(), "font_sha256": font_hash,
        "font_copied": False, "pixel_size": 16, "threshold": 128, "glyph_count": len(ids),
        "glyphs": [{"char": char, "id": code, "rows_hex": [f"{v:04X}" for v in font_rows[code]]} for char, code in sorted(ids.items(), key=lambda pair: pair[1])],
        "source_root": SOURCE_ROOT, "derivation_sources": SOURCES,
        "outputs": [{"path": p.relative_to(repo).as_posix(), "sha256": sha256(p)} for p in output_paths],
        "previews": previews,
        "layout": {"video": [1280,720], "panel_x": [32,1248], "panel_y": [[8,112],[608,712]],
                   "text_x": [48,1232], "line_y": [12,44,76,612,644,676], "cell_pixels": [32,32],
                   "unobscured_center_roi": [320,120,960,600], "output_latency_clocks": 1},
    })
    print(f"ITEMS14_FONT glyphs={len(ids)} texts={len(TEXTS)} previews={len(previews)} max_columns={max(map(len,TEXTS))} font_sha256={font_hash}")


if __name__ == "__main__":
    main()
